export interface IconProps {
  className?: string;
  /** Decorative by default; pass a label to make it announced. */
  label?: string;
}

const STROKE = {
  xmlns: 'http://www.w3.org/2000/svg',
  fill: 'none',
  viewBox: '0 0 24 24',
  strokeWidth: 1.5,
  stroke: 'currentColor',
  strokeLinecap: 'round',
  strokeLinejoin: 'round',
} as const;

const FILL = {
  xmlns: 'http://www.w3.org/2000/svg',
  viewBox: '0 0 24 24',
  fill: 'currentColor',
} as const;

function a11y(label?: string): { 'aria-hidden': true } | { role: 'img'; 'aria-label': string } {
  return label === undefined ? { 'aria-hidden': true } : { role: 'img', 'aria-label': label };
}

/** Factory for the stroke icons — keeps 30 near-identical components to one line each. */
function stroke(d: string | string[]) {
  const paths = Array.isArray(d) ? d : [d];
  return function Icon({ className = 'h-5 w-5', label }: IconProps) {
    return (
      <svg {...STROKE} className={className} {...a11y(label)}>
        {paths.map((p) => (
          <path key={p} d={p} />
        ))}
      </svg>
    );
  };
}

function fill(d: string) {
  return function Icon({ className = 'h-4 w-4', label }: IconProps) {
    return (
      <svg {...FILL} className={className} {...a11y(label)}>
        <path d={d} />
      </svg>
    );
  };
}

